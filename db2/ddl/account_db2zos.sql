CREATE TABLE Z79583.ACCOUNT
  (ACCOUNT_NUMBER  DECIMAL(10,0)  NOT NULL,
   NAME            CHAR(30)       NOT NULL,
   ACCOUNT_TYPE    CHAR(1)        NOT NULL,
   BALANCE         DECIMAL(11,2)  NOT NULL WITH DEFAULT 0,
   OPENING_DATE    DATE           NOT NULL,
   STATUS          CHAR(1)        NOT NULL WITH DEFAULT 'A',
   CONSTRAINT PK_ACCOUNT
     PRIMARY KEY (ACCOUNT_NUMBER),
   CONSTRAINT CK_ACCOUNT_TYPE
     CHECK (ACCOUNT_TYPE IN ('S','C')),
   CONSTRAINT CK_STATUS
     CHECK (STATUS IN ('A','B','C')),
   CONSTRAINT CK_BALANCE
     CHECK (BALANCE >= 0)
  );
--
COMMENT ON TABLE Z79583.ACCOUNT
  IS 'BANK ACCOUNTS - DB2 PRACTICE TABLE';
COMMENT ON COLUMN Z79583.ACCOUNT.ACCOUNT_TYPE
  IS 'S=SAVINGS, C=CHECKING';
COMMENT ON COLUMN Z79583.ACCOUNT.STATUS
  IS 'A/B/C - ACCOUNT STATUS';
--
COMMIT;
